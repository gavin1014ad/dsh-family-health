    function uid() {
      try {
        if (window.crypto && typeof window.crypto.randomUUID === "function") return window.crypto.randomUUID();
      } catch (error) {
        /* fall through */
      }
      return `fh-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 9)}`;
    }

    function isRecord(value) {
      return typeof value === "object" && value !== null && !Array.isArray(value);
    }

    function clampText(value, max) {
      return String(value || "").slice(0, max);
    }

    function sanitizeMember(value) {
      if (!isRecord(value)) return null;
      const name = clampText(value.name, MAX_NAME);
      if (name.trim() === "") return null;
      return {
        id: typeof value.id === "string" && value.id !== "" ? value.id : uid(),
        name,
        relation: clampText(value.relation, MAX_RELATION),
        gender: value.gender === "female" ? "female" : "male",
        color: typeof value.color === "string" && value.color !== "" ? value.color : "#3EC9A7",
        birthYear: clampText(value.birthYear, 4),
      };
    }

