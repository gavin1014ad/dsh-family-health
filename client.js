    function TrendPanel({ state, t }) {
      const keys = useMemo(() => {
        const set = new Set();
        for (const exam of state.exams) {
          for (const mk of exam.markers) set.add(mk.key);
        }
        return Array.from(set).sort((a, b) => (MARKER_DEFS[a]?.name || a).localeCompare(MARKER_DEFS[b]?.name || b));
      }, [state.exams]);
      const [selected, setSelected] = useState(keys[0] || "");

      useEffect(() => {
        if (selected !== "" && !keys.includes(selected)) setSelected(keys[0] || "");
      }, [keys, selected]);

      const rows = useMemo(() => {
        if (selected === "") return [];
        const out = [];
        for (const exam of state.exams) {
          const mk = exam.markers.find((m) => m.key === selected);
          if (mk === undefined) continue;
          const member = state.members.find((m) => m.id === exam.memberId);
          out.push({ member, exam, mk });
        }
        return out.sort((a, b) => (a.exam.date || "").localeCompare(b.exam.date || ""));
      }, [state, selected]);

      const values = rows.map((r) => parseFloat(r.mk.value)).filter((v) => Number.isFinite(v));
      const maxVal = values.length > 0 ? Math.max(...values) : 0;
      const minVal = values.length > 0 ? Math.min(...values) : 0;

      const def = MARKER_DEFS[selected];

      return h(
        "div",
        null,
        h("p", { className: "fh-trendHint" }, t("selectTrendHint")),
        h(
          "select",
          { className: "fh-trendSelect", value: selected, onChange: (e) => setSelected(e.target.value), "aria-label": t("trends") },
          keys.map((k) => h("option", { key: k, value: k }, (MARKER_DEFS[k]?.name || k) + (MARKER_DEFS[k]?.unit ? " (" + MARKER_DEFS[k].unit + ")" : ""))),
        ),
        selected === ""
          ? h("div", { className: "fh-empty" }, t("trendEmpty"))
          : h(
              "div",
              { className: "fh-trendCard" },
              h("div", { className: "fh-trendTitle" }, def ? def.name : selected),
              def && def.unit ? h("span", { className: "fh-trendUnit" }, " " + def.unit) : null,
              rows.length === 0
                ? h("div", { className: "fh-empty" }, t("trendEmpty"))
                : h(
                    "div",
                    { className: "fh-trendList" },
                    rows.map(({ member, exam, mk }) => {
                      const num = parseFloat(mk.value);
                      const ratio = Number.isFinite(num) && maxVal > minVal ? (num - minVal) / (maxVal - minVal || 1) : 0.5;
                      return h(
                        "div",
                        { key: exam.id + mk.key, className: "fh-trendRow" },
                        h("span", { className: "fh-trendName", title: member ? memberLabel(member, t) : exam.memberId }, member ? memberLabel(member, t) : exam.memberId),
                        h("span", { className: "fh-trendVal", "data-flag": mk.flag }, mk.value),
                        h("span", { className: "fh-bar", title: mk.value }, h("span", { className: "fh-barFill", style: { width: `${Math.round(ratio * 100)}%`, backgroundColor: mk.flag === "high" ? "var(--dsw-alias-state-error-primary)" : mk.flag === "low" ? "var(--dsw-alias-brand-primary)" : "var(--dsw-alias-state-success-primary)" } })),
                        h("span", { className: "fh-trendDate" }, formatDate(exam.date)),
                      );
                    }),
                  ),
            ),
      );
    }

    function FamilyHealth({ t }) {
      const [state, setState] = useState(() => {
        const stored = readState();
        return stored === null ? defaultState() : stored;
      });
      const [selectedId, setSelectedId] = useState(() => {
        const stored = readState();
        const list = stored === null ? SEED_MEMBERS : stored.members;
        return list.length > 0 ? list[0].id : "";
      });
      const [view, setView] = useState("overview");
      const [memberDialog, setMemberDialog] = useState(null);
      const [pendingDelete, setPendingDelete] = useState(null);
      const [exportMember, setExportMember] = useState(null);
      const [examDialog, setExamDialog] = useState(null);
      const stateRef = useRef(state);
      stateRef.current = state;

      useEffect(() => {
        const timer = window.setTimeout(() => writeState(stateRef.current), 120);
        return () => window.clearTimeout(timer);
      }, [state]);

      useEffect(() => () => writeState(stateRef.current), []);

      // keep a valid selection when members change
      useEffect(() => {
        if (state.members.length === 0) {
          setSelectedId("");
        } else if (!state.members.some((m) => m.id === selectedId)) {
          setSelectedId(state.members[0].id);
        }
      }, [state.members, selectedId]);

      const saveMember = (draft) => {
        setState((prev) => {
          if (memberDialog && memberDialog.mode === "edit" && memberDialog.id) {
            return {
              ...prev,
              members: prev.members.map((m) => (m.id === memberDialog.id ? { ...m, name: draft.name, relation: draft.relation, gender: draft.gender } : m)),
            };
          }
          const color = ["#3E8DE3", "#E36A9C", "#9B6BE3", "#3EC9A7", "#E3A23E", "#5BA8C9"][prev.members.length % 6];
          return {
            ...prev,
            members: [...prev.members, { id: uid(), name: draft.name, relation: draft.relation, gender: draft.gender, color, birthYear: "" }],
          };
        });
        setMemberDialog(null);
      };

      const confirmDelete = () => {
        if (pendingDelete === null) return;
        const id = pendingDelete.id;
        setState((prev) => {
          const risks = { ...(prev.risks || {}) };
          const advice = { ...(prev.advice || {}) };
          delete risks[id];
          delete advice[id];
          return {
            ...prev,
            members: prev.members.filter((m) => m.id !== id),
            exams: prev.exams.filter((e) => e.memberId !== id),
            risks,
            advice,
          };
        });
        setPendingDelete(null);
        setMemberDialog(null);
      };

      const saveExam = (draft) => {
        if (examDialog === null) return;
        const memberId = examDialog.memberId;
        const exam = {
          id: uid(),
          memberId,
          date: draft.date,
          hospital: draft.hospital,
          title: draft.title,
          findings: draft.findings,
          markers: draft.markers,
        };
        setState((prev) => ({ ...prev, exams: [...prev.exams, exam] }));
        setExamDialog(null);
      };

      const memberRail = h(
        "div",
        { className: "fh-memberRail", role: "tablist", "aria-label": t("members") },
        state.members.map((m) =>
          h(
            "button",
            {
              key: m.id, type: "button", className: "fh-memberChip", role: "tab",
              "aria-selected": selectedId === m.id, "aria-pressed": selectedId === m.id,
              onClick: () => { setSelectedId(m.id); setView("overview"); },
            },
            h("span", { className: "fh-avatar", style: { backgroundColor: m.color } }, avatarInitial(m.name)),
            h("span", null, m.name),
          ),
        ),
        h(
          "button",
          { type: "button", className: "fh-memberChip", style: { borderStyle: "dashed" }, onClick: () => setMemberDialog({ mode: "create", id: null }) },
          h(Icon, { name: "plus", size: 14 }),
          h("span", null, t("addMember")),
        ),
      );

      const header = h(
        "header",
        { className: "fh-header" },
        h(
          "div",
          { className: "fh-titleGroup" },
          h("span", { className: "fh-logo" }, h(ShieldMark, { size: 20 })),
          h(
            "div",
            { style: { minWidth: 0 } },
            h("h1", { className: "fh-title" }, t("panel")),
            h("p", { className: "fh-subtitle" }, t("subtitle")),
          ),
        ),
        h(
          "div",
          { className: "fh-viewToggle", role: "group", "aria-label": t("panel") },
          h("button", { type: "button", className: "fh-viewBtn", "aria-pressed": view === "overview", onClick: () => setView("overview") }, t("overview")),
          h("button", { type: "button", className: "fh-viewBtn", "aria-pressed": view === "trends", onClick: () => setView("trends") }, t("trends")),
        ),
      );

      const body = view === "trends"
        ? h(TrendPanel, { state, t })
        : h(MemberPanel, {
            state,
            selectedId,
            t,
            onSelect: (id) => setSelectedId(id),
            onAdd: () => setMemberDialog({ mode: "create", id: null }),
            onEdit: (member) => setMemberDialog({ mode: "edit", id: member.id }),
            onDelete: (member) => setPendingDelete(member),
            onExport: (member) => setExportMember(member),
            onAddExam: (member) => setExamDialog({ memberId: member.id }),
          });

      const dialogNode = memberDialog === null
        ? null
        : h(MemberDialog, {
            key: memberDialog.mode + ":" + (memberDialog.id || "new"),
            initial: memberDialog.mode === "edit" ? state.members.find((m) => m.id === memberDialog.id) : null,
            t,
            onCancel: () => setMemberDialog(null),
            onSave: saveMember,
          });

      const examNode = examDialog === null
        ? null
        : h(ExamDialog, {
            key: examDialog.memberId,
            member: state.members.find((m) => m.id === examDialog.memberId) || null,
            t,
            onCancel: () => setExamDialog(null),
            onSave: saveExam,
          });

      const exportNode = exportMember === null
        ? null
        : h(ExportDialog, {
            key: exportMember.id,
            reportHtml: buildReportHtml(state, exportMember, t),
            memberName: exportMember.name,
            t,
            onCancel: () => setExportMember(null),
          });

      const deleteNode = pendingDelete === null
        ? null
        : h(DeleteDialog, {
            key: pendingDelete.id,
            name: pendingDelete.name,
            t,
            onCancel: () => setPendingDelete(null),
            onConfirm: confirmDelete,
          });

      return h(
        "div",
        { className: "fh-root" },
        h("style", null, CSS),
        header,
        memberRail,
        h("div", { className: "fh-body" }, body),
        dialogNode,
        examNode,
        exportNode,
        deleteNode,
      );
    }

