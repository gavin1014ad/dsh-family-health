    function readState() {
      try {
        const raw = window.localStorage.getItem(STORAGE_KEY);
        if (raw === null) return null;
        const parsed = JSON.parse(raw);
        if (!isRecord(parsed) || !Array.isArray(parsed.members)) return null;
        const members = parsed.members.map(sanitizeMember).filter(Boolean);
        const exams = Array.isArray(parsed.exams) ? parsed.exams.map(sanitizeExam).filter(Boolean) : [];
        // risks: object keyed by memberId -> array of risk
        const risks = {};
        if (isRecord(parsed.risks)) {
          for (const [memberId, list] of Object.entries(parsed.risks)) {
            if (Array.isArray(list)) risks[memberId] = list.map(sanitizeRisk).filter(Boolean);
          }
        }
        const advice = {};
        if (isRecord(parsed.advice)) {
          for (const [memberId, a] of Object.entries(parsed.advice)) {
            advice[memberId] = sanitizeAdvice(a);
          }
        }
        // Fall back to seed risks/advice for members missing them (e.g. data
        // saved by an older plugin version that had no risk analysis yet).
        for (const memberId of Object.keys(SEED_RISKS)) {
          if (!Array.isArray(risks[memberId]) || risks[memberId].length === 0) {
            risks[memberId] = SEED_RISKS[memberId].map((r) => ({ ...r }));
          }
        }
        for (const memberId of Object.keys(SEED_ADVICE)) {
          if (!advice[memberId] || advice[memberId].items.length === 0) {
            advice[memberId] = { summary: SEED_ADVICE[memberId].summary, items: SEED_ADVICE[memberId].items.map((it) => ({ ...it })) };
          }
        }
        return { version: 2, members, exams, risks, advice };
      } catch (error) {
        return null;
      }
    }

